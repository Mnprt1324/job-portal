const {test}=require('node:test');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const {io:client}=require('socket.io-client');
const {fixture}=require('./helpers/messagingFixture.cjs');
const Conversation=require('../models/conversation.model');
const Message=require('../models/message.model');
const Job=require('../models/job.model');
const User=require('../models/user.model');
const service=require('../services/messaging.service');
const once=(socket,event)=>new Promise((resolve,reject)=>{const timer=setTimeout(()=>{socket.off(event,handler);reject(new Error(`Timed out: ${event}`));},5000);const handler=data=>{clearTimeout(timer);resolve(data);};socket.once(event,handler);});
test('Messaging persists both directions, protects membership, retries safely and recovers history',{timeout:120000},async t=>{
  const f=await fixture();t.after(()=>f.close());
  const {company,seeker,outsider,otherCompany,admin,application,request}=f;
  assert.equal((await request(null,'/conversations')).status,401);
  assert.equal((await request(admin,'/conversations')).status,403);
  assert.equal((await request(outsider,'/conversations','POST',{applicationId:application.id})).status,404);
  assert.equal((await request(otherCompany,'/conversations','POST',{applicationId:application.id})).status,404);
  const results=await Promise.all([company,seeker,company].map(user=>request(user,'/conversations','POST',{applicationId:application.id})));
  for(const result of results)assert.equal(result.status,200);
  const id=results[0].body.conversation._id;
  assert.equal(new Set(results.map(r=>r.body.conversation._id)).size,1);
  assert.equal(await Conversation.countDocuments({}),1);
  assert.equal((await request(outsider,`/conversations/${id}/messages`)).status,404);
  assert.equal((await request(company,`/conversations/${id}/messages?beforeSequence=1&afterSequence=0`)).status,400);
  assert.equal((await request(company,`/conversations/${id}/messages`,'POST',{content:' ',clientMessageId:randomUUID()})).status,400);
  assert.equal((await request(company,`/conversations/${id}/messages`,'POST',{content:'x'.repeat(2001),clientMessageId:randomUUID()})).status,400);
  assert.equal((await request(company,`/conversations/${id}/messages`,'POST',{content:'Hello',clientMessageId:'not-a-uuid'})).status,400);
  const socket=client(f.base,{autoConnect:false,auth:{token:f.token(seeker)}});
  const badSocket=client(f.base,{autoConnect:false,auth:{token:'invalid'}});
  t.after(()=>{socket.disconnect();badSocket.disconnect();});
  const connected=once(socket,'connect');socket.connect();await connected;
  const denied=once(badSocket,'connect_error');badSocket.connect();await denied;
  const received=once(socket,'message:created');
  const uuid=randomUUID(),sendBody={content:'Hello Asha, we liked your application.',clientMessageId:uuid};
  const sent=await request(company,`/conversations/${id}/messages`,'POST',sendBody);
  assert.equal(sent.status,201);assert.equal(sent.body.message.sequence,1);
  const event=await received;assert.equal(event._id,sent.body.message._id);
  const retried=await request(company,`/conversations/${id}/messages`,'POST',sendBody);
  assert.equal(retried.status,200);assert.equal(retried.body.message._id,event._id);
  assert.equal((await request(company,`/conversations/${id}/messages`,'POST',{...sendBody,content:'Different'})).status,409);
  assert.equal((await request(seeker,'/conversations/unread')).body.unread,1);
  const reply=await request(seeker,`/conversations/${id}/messages`,'POST',{content:'Thank you! I would love to hear more.',clientMessageId:randomUUID()});
  assert.equal(reply.status,201);assert.equal(reply.body.message.sequence,2);
  assert.equal((await request(company,'/conversations/unread')).body.unread,1);
  await request(seeker,`/conversations/${id}/read`,'PATCH',{throughSequence:2});
  await request(seeker,`/conversations/${id}/read`,'PATCH',{throughSequence:1});
  assert.equal((await Conversation.findById(id)).jobseekerLastReadSequence,2);
  assert.equal((await request(seeker,'/conversations/unread')).body.unread,0);
  assert.equal((await request(seeker,`/conversations/${id}/read`,'PATCH',{throughSequence:99})).status,400);
  const concurrentId=randomUUID();
  const concurrent=await Promise.all([1,2].map(()=>request(company,`/conversations/${id}/messages`,'POST',{content:'A time for a conversation?',clientMessageId:concurrentId})));
  assert.ok(concurrent.every(r=>[200,201].includes(r.status)));assert.equal(new Set(concurrent.map(r=>r.body.message._id)).size,1);
  const more=await Promise.all(Array.from({length:7},(_,i)=>request(company,`/conversations/${id}/messages`,'POST',{content:`Follow-up ${i}`,clientMessageId:randomUUID()})));
  assert.ok(more.every(r=>r.status===201));
  const last=await request(seeker,`/conversations/${id}/messages?limit=3`);
  assert.equal(last.body.messages.length,3);assert.equal(last.body.hasMore,true);
  const older=await request(seeker,`/conversations/${id}/messages?beforeSequence=${last.body.messages[0].sequence}&limit=3`);
  assert.ok(older.body.messages.at(-1).sequence<last.body.messages[0].sequence);
  let after=2,recovered=[];let page;
  do{page=await request(seeker,`/conversations/${id}/messages?afterSequence=${after}&limit=3`);recovered.push(...page.body.messages);after=page.body.messages.at(-1)?.sequence||after;}while(page.body.hasMore);
  assert.deepEqual(recovered.map(m=>m.sequence),[3,4,5,6,7,8,9,10]);
  assert.equal(await Message.countDocuments({conversationId:id}),10);
  const list=await request(company,'/conversations');assert.equal(list.body.conversations[0].partnerName,'Asha Sharma');
  assert.equal(list.body.conversations[0].unread,1);
  const forbiddenJoin=await new Promise(resolve=>{const other=client(f.base,{auth:{token:f.token(outsider)}});other.on('connect',()=>other.emit('conversation:join',id,result=>{other.disconnect();resolve(result);}));});
  assert.equal(forbiddenJoin.success,false);
  await Job.findByIdAndUpdate(f.job._id,{deletedAt:new Date()});
  assert.equal((await request(company,`/conversations/${id}/messages`,'POST',{content:'Should not send',clientMessageId:randomUUID()})).status,409);
  assert.match((await request(seeker,`/conversations/${id}/messages`)).body.conversation.readOnlyReason,/read-only/);
  await Job.findByIdAndUpdate(f.job._id,{deletedAt:null});
  await User.findByIdAndUpdate(company._id,{isSuspended:true});
  assert.equal((await request(company,'/conversations')).status,403);
  assert.equal((await request(seeker,`/conversations/${id}/messages`,'POST',{content:'Unavailable',clientMessageId:randomUUID()})).status,409);
});
test('Message input and role limits reject malformed data',()=>{
  assert.throws(()=>service.validateMessage({content:[],clientMessageId:randomUUID()}),/message/);
  assert.throws(()=>service.participantFilter({_id:'x',role:'admin'}),/companies and jobseekers/);
  for(const value of ['bad',-1,101,1.5])assert.throws(()=>service.limitValue(value,30,100),/page size/);
});
